/* ---------------- Hard todos file based ---------------- */

const express = require("express");
const bodyParser = require("body-parser");
const fs = require("fs");

const app = express();

app.use(bodyParser.json());

/* ---------------- Read Todo Helper Function ---------------- */

function readTodos(callback) {
  fs.readFile("todos.json", "utf-8", (err, data) => {
    if (err) {
      return callback(err);
    }

    const todos = JSON.parse(data || "[]");

    callback(null, todos);
  });
}

/* ---------------- Write Todo Helper Function ---------------- */

function writeTodos(todos, callback) {
  fs.writeFile("todos.json", JSON.stringify(todos, null, 2), "utf-8", (err) => {
    if (err) {
      return callback(err);
    }

    callback(null);
  });
}

/* ---------------- GET all todos ---------------- */

app.get("/todos", (req, res) => {
  readTodos((err, todos) => {
    if (err) {
      return res.status(500).send();
    }

    res.status(200).json(todos);
  });
});

/* ---------------- GET todo by ID ---------------- */

app.get("/todos/:id", (req, res) => {
  const id = parseInt(req.params.id);

  readTodos((err, todos) => {
    if (err) {
      return res.status(500).send();
    }

    const todo = todos.find((t) => t.id === id);

    if (!todo) {
      return res.status(404).json({ error: "Todo not found" });
    }

    res.status(200).json(todo);
  });
});

/* ---------------- CREATE new todo ---------------- */

app.post("/todos", (req, res) => {
  const { title, description } = req.body;

  readTodos((err, todos) => {
    if (err) {
      return res.status(500).send();
    }

    const newTodo = {
      id: Date.now(),
      title,
      description,
    };

    todos.push(newTodo);

    writeTodos(todos, (err) => {
      if (err) {
        return res.status(500).send();
      }

      res.status(201).json({ id: newTodo.id });
    });
  });
});

/* ---------------- UPDATE todo ---------------- */

app.put("/todos/:id", (req, res) => {
  const id = parseInt(req.params.id);

  readTodos((err, todos) => {
    if (err) {
      return res.status(500).send();
    }

    const index = todos.findIndex((t) => t.id === id);

    if (index === -1) {
      return res.status(404).json({ error: "Todo not found" });
    }

    const { title, description } = req.body;

    todos[index] = {
      id,
      title,
      description,
    };

    writeTodos(todos, (err) => {
      if (err) {
        return res.status(500).send();
      }

      res.status(200).json(todos[index]);
    });
  });
});

/* ---------------- DELETE todo ---------------- */

app.delete("/todos/:id", (req, res) => {
  const id = parseInt(req.params.id);

  readTodos((err, todos) => {
    if (err) {
      return res.status(500).send();
    }

    const index = todos.findIndex((t) => t.id === id);

    if (index == -1) {
      return res.status(404).json({ error: "Todo not found" });
    }

    // remove todo
    todos.splice(index, 1);

    writeTodos(todos, (err) => {
      if (err) {
        return res.status(500).send();
      }

      res.status(200).send();
    });
  });
});

/* ---------------- Unknown routes ---------------- */

app.use((req, res) => {
  res.status(404).json({ error: "Route not found" });
});

module.exports = app;
